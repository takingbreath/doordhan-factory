#!/usr/bin/env python3
"""Narrow Bash entry points for the resumable loop: checkpoint init/status OR gate-checked preview.
Approval commands are deliberately unavailable to these agents. The human conversation records them.
"""
import json
import re
import shlex
import sys

try:
    mode = sys.argv[1]
    command = (json.load(sys.stdin).get('tool_input') or {}).get('command', '')
    args = shlex.split(command)
    slug = lambda value: re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]*', value) is not None
    valid = False
    if mode == 'checkpoint' and args[:2] == ['python3', 'pipeline/reel_script_gate.py']:
        valid = ((len(args) == 4 and args[2] == 'status' and slug(args[3]))
                 or (len(args) == 5 and args[2:4] == ['init', '--payload']
                     and isinstance(json.loads(args[4]), dict)))
    elif mode == 'preview' and args[:2] == ['python3', 'pipeline/reel_voice_preview.py']:
        rest = args[3:]
        valid = (len(args) >= 3 and slug(args[2]) and len(rest) % 2 == 0
                 and all(rest[i] == '--retake' and re.fullmatch(r'[A-Za-z0-9-]+', rest[i + 1])
                         for i in range(0, len(rest), 2)))
    # shlex alone does not reject shell expansion: only allow an argv-preserving, safely quoted command.
    # For payloads, canonical single-quote escaping is generated by the workflow; other args have no shell syntax.
    if valid:
        if mode == 'checkpoint' and args[2] == 'init':
            quoted = "'" + args[4].replace("'", "'\\''") + "'"
            valid = command == 'python3 pipeline/reel_script_gate.py init --payload ' + quoted
        else:
            valid = not re.search(r'[;&|`$<>\r\n]', command)
    if valid:
        sys.exit(0)
except (IndexError, TypeError, ValueError, AttributeError):
    pass
print('Blocked: this agent may only inspect/initialize the draft checkpoint or run its gate-checked preview; '
      'it cannot approve a human decision or invoke an unguarded renderer.', file=sys.stderr)
sys.exit(2)
